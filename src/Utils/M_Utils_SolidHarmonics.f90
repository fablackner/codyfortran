!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
!> Real regular solid harmonics S_lm(x, y, z) in Racah normalization.
!>
!> S_lm = sqrt(4 pi/(2l+1)) r^l Y_lm with the real spherical harmonics Y_lm
!> (m > 0: cos(m phi), m < 0: sin(|m| phi) type), generated by the
!> Helgaker/Jorgensen/Olsen recursion
!>   S_00         = 1,
!>   S_(l+1,l+1)  = f_l (x S_ll - (1 - d_l0) y S_(l,-l)),
!>   S_(l+1,-l-1) = f_l (y S_ll + (1 - d_l0) x S_(l,-l)),  f_l = sqrt(2^d_l0 (2l+1)/(2l+2)),
!>   S_(l+1,m)    = ((2l+1) z S_lm - sqrt((l+m)(l-m)) r^2 S_(l-1,m)) / sqrt((l+m+1)(l-m+1)),  |m| <= l,
!> so that S_10 = z, S_11 = x, S_1-1 = y, S_20 = (3z^2 - r^2)/2,
!> S_21 = sqrt(3) xz, S_2-1 = sqrt(3) yz, S_22 = sqrt(3)/2 (x^2 - y^2),
!> S_2-2 = sqrt(3) xy, and the addition theorem reads
!>   1/|r1 - r2| = sum_lm S_lm(r1) S_lm(r2) / |r2|^(2l+1)   (|r1| < |r2|).
!>
!> Two forms of the same recursion: polynomial coefficients
!> (SolidHarmonics_FillCoefficients, for moments and multipole expansions)
!> and values at a point (SolidHarmonics_FillValues). Tables are indexed by
!> SolidHarmonics_LmIndex(l, m) = l^2 + l + m + 1. Stateless and thread-safe.
module M_Utils_SolidHarmonics
  use M_Utils_Types

  implicit none

  private :: TimesCoordinate

contains

!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
  !> Position of (l, m), |m| <= l, in the solid harmonic tables: l^2 + l + m + 1.
  pure function SolidHarmonics_LmIndex(l, m) result(res)

    integer(I32), intent(in) :: l
    integer(I32), intent(in) :: m
    integer(I32) :: res

    res = l * l + l + m + 1

  end function

!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
  !> Polynomial coefficients of S_lm, 0 <= l <= lmax:
  !>   S_lm(x, y, z) = sum_(a+b+c=l) coeffs(a, b, c, SolidHarmonics_LmIndex(l, m)) x^a y^b z^c,
  !> coeffs(0:lmax, 0:lmax, 0:lmax, (lmax+1)^2), by running the recursion on the
  !> coefficient arrays.
  subroutine SolidHarmonics_FillCoefficients(coeffs, lmax)

    real(R64), allocatable, intent(out) :: coeffs(:, :, :, :)
    integer(I32), intent(in)            :: lmax

    real(R64) :: factor, cross
    integer(I32) :: l, m, lmTop, lmBottom, lmNext, lmThis, lmPrevious

    ! The table positions are kept in plain variables: gfortran 15.2 with
    ! -fcheck=bounds reads an uninitialized temporary for an expression
    ! argument (e.g. -l) of a function call used as a section subscript here
    allocate (coeffs(0:lmax, 0:lmax, 0:lmax, (lmax + 1)**2))
    coeffs = 0.0_R64
    coeffs(0, 0, 0, SolidHarmonics_LmIndex(0, 0)) = 1.0_R64

    do l = 0, lmax - 1

      ! f_0 = 1 and no cross term for l = 0 (S_(0,-0) = S_00)
      if (l .eq. 0) then
        factor = 1.0_R64
        cross = 0.0_R64
      else
        factor = sqrt(real(2 * l + 1, R64) / real(2 * l + 2, R64))
        cross = 1.0_R64
      end if

      ! S_(l+1,l+1) and S_(l+1,-l-1) from S_ll and S_(l,-l)
      lmTop = SolidHarmonics_LmIndex(l, l)
      lmBottom = SolidHarmonics_LmIndex(l, -l)

      lmNext = SolidHarmonics_LmIndex(l + 1, l + 1)
      coeffs(:, :, :, lmNext) = factor * (TimesCoordinate(coeffs(:, :, :, lmTop), 1) - &
                                          cross * TimesCoordinate(coeffs(:, :, :, lmBottom), 2))

      lmNext = SolidHarmonics_LmIndex(l + 1, -l - 1)
      coeffs(:, :, :, lmNext) = factor * (TimesCoordinate(coeffs(:, :, :, lmTop), 2) + &
                                          cross * TimesCoordinate(coeffs(:, :, :, lmBottom), 1))

      ! S_(l+1,m), |m| <= l, from S_lm and r^2 S_(l-1,m)
      do m = -l, l
        lmThis = SolidHarmonics_LmIndex(l, m)
        lmNext = SolidHarmonics_LmIndex(l + 1, m)

        coeffs(:, :, :, lmNext) = real(2 * l + 1, R64) * TimesCoordinate(coeffs(:, :, :, lmThis), 3)

        if (l - 1 >= abs(m)) then
          lmPrevious = SolidHarmonics_LmIndex(l - 1, m)
          coeffs(:, :, :, lmNext) = coeffs(:, :, :, lmNext) - &
                                    sqrt(real((l + m) * (l - m), R64)) * &
                                    (TimesCoordinate(TimesCoordinate(coeffs(:, :, :, lmPrevious), 1), 1) + &
                                     TimesCoordinate(TimesCoordinate(coeffs(:, :, :, lmPrevious), 2), 2) + &
                                     TimesCoordinate(TimesCoordinate(coeffs(:, :, :, lmPrevious), 3), 3))
        end if

        coeffs(:, :, :, lmNext) = coeffs(:, :, :, lmNext) / sqrt(real((l + m + 1) * (l - m + 1), R64))
      end do

    end do

  end subroutine

!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
  !> Values S_lm(r), 0 <= l <= lmax, at the point r = (x, y, z):
  !> values(SolidHarmonics_LmIndex(l, m)), size(values) >= (lmax + 1)^2. The
  !> recursion has no divisions by r, so r = 0 is regular (S_00 = 1, all
  !> others 0).
  pure subroutine SolidHarmonics_FillValues(values, r, lmax)

    real(R64), intent(out)   :: values(:)
    real(R64), intent(in)    :: r(3)
    integer(I32), intent(in) :: lmax

    real(R64) :: r2, factor, cross, top, bottom, value
    integer(I32) :: l, m

    r2 = r(1) * r(1) + r(2) * r(2) + r(3) * r(3)

    values(SolidHarmonics_LmIndex(0, 0)) = 1.0_R64

    do l = 0, lmax - 1

      ! f_0 = 1 and no cross term for l = 0 (S_(0,-0) = S_00)
      if (l .eq. 0) then
        factor = 1.0_R64
        cross = 0.0_R64
      else
        factor = sqrt(real(2 * l + 1, R64) / real(2 * l + 2, R64))
        cross = 1.0_R64
      end if

      ! S_(l+1,l+1) and S_(l+1,-l-1) from S_ll and S_(l,-l)
      top = values(SolidHarmonics_LmIndex(l, l))
      bottom = values(SolidHarmonics_LmIndex(l, -l))

      values(SolidHarmonics_LmIndex(l + 1, l + 1)) = factor * (r(1) * top - cross * r(2) * bottom)
      values(SolidHarmonics_LmIndex(l + 1, -l - 1)) = factor * (r(2) * top + cross * r(1) * bottom)

      ! S_(l+1,m), |m| <= l, from S_lm and r^2 S_(l-1,m)
      do m = -l, l
        value = real(2 * l + 1, R64) * r(3) * values(SolidHarmonics_LmIndex(l, m))

        if (l - 1 >= abs(m)) then
          value = value - sqrt(real((l + m) * (l - m), R64)) * r2 * values(SolidHarmonics_LmIndex(l - 1, m))
        end if

        values(SolidHarmonics_LmIndex(l + 1, m)) = value / sqrt(real((l + m + 1) * (l - m + 1), R64))
      end do

    end do

  end subroutine

!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
  !> Coefficients of x_iAxis P for a polynomial P (coefficients poly(a, b, c) of
  !> x^a y^b z^c) of degree below the table size in that coordinate.
  pure function TimesCoordinate(poly, iAxis) result(res)

    real(R64), intent(in)    :: poly(0:, 0:, 0:)
    integer(I32), intent(in) :: iAxis
    real(R64) :: res(0:ubound(poly, 1), 0:ubound(poly, 2), 0:ubound(poly, 3))

    integer(I32) :: n

    res = 0.0_R64

    select case (iAxis)
    case (1)
      n = ubound(poly, 1)
      res(1:n, :, :) = poly(0:n - 1, :, :)
    case (2)
      n = ubound(poly, 2)
      res(:, 1:n, :) = poly(:, 0:n - 1, :)
    case default
      n = ubound(poly, 3)
      res(:, :, 1:n) = poly(:, :, 0:n - 1)
    end select

  end function

end module
