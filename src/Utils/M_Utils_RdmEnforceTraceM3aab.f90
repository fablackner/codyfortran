    if (nDim <= 4) error stop "RdmEnforceTraceM3aab: contraction consistency requires more than 4 orbitals"

    x = dble(nDim)

    pa(1, 1) = (8 - 4 * x + x**2) / ((-4 + x) * (-3 + x) * x * (-4 + x**2))
