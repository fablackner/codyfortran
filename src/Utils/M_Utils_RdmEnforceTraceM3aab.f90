    pa(5, 1) = (-4 + 3 * x) / ((-4 + x) * (-3 + x) * x * (-4 + x**2))
    pa(6, 1) = (4 - 3 * x) / ((-4 + x) * (-3 + x) * x * (-4 + x**2))
    pa(1, 2) = (2 * (4 - 3 * x)) / ((-4 + x) * (-3 + x) * x * (-4 + x**2))
    pa(2, 2) = (4 - x + x**2) / ((-4 + x) * (-3 + x) * x * (-4 + x**2))
    pa(3, 2) = (2 * (-4 + 3 * x)) / ((-4 + x) * (-3 + x) * x * (-4 + x**2))
